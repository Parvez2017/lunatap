"""Interactive setup wizard for first-time Lunatap onboarding (lunatap init)."""

from rich.console import Console
from rich.panel import Panel
from rich.prompt import Prompt

from lunatap.config.paths import get_env_file


def init_command() -> None:
    """Interactive quickstart wizard to configure API keys and connect your device."""
    console = Console()
    console.print()
    console.print(
        Panel(
            "[bold cyan]🌙 Welcome to Lunatap, the AI testing agent for iOS[/bold cyan]\n"
            "[dim]Let's get you set up in 10 seconds![/dim]",
            expand=False,
        )
    )

    # 1. Select Provider
    console.print("\n[bold]Step 1: Choose Primary LLM Provider[/bold]")
    console.print("  [1] Google Gemini (Recommended - Default)")
    console.print("  [2] OpenAI (GPT-5.4)")
    console.print("  [3] Anthropic (Claude)")
    console.print("  [4] OpenRouter")

    choice = Prompt.ask("Select provider", choices=["1", "2", "3", "4"], default="1")
    provider_map = {
        "1": ("GEMINI_API_KEY", "Google Gemini"),
        "2": ("OPENAI_API_KEY", "OpenAI"),
        "3": ("ANTHROPIC_API_KEY", "Anthropic"),
        "4": ("OPEN_ROUTER_API_KEY", "OpenRouter"),
    }
    env_key, provider_name = provider_map[choice]

    # 2. Enter API Key
    console.print(f"\n[bold]Step 2: Enter your {provider_name} API Key[/bold]")
    api_key = Prompt.ask(f"Enter {env_key}", password=True)
    while not api_key.strip():
        console.print("[bold red]API Key cannot be empty.[/bold red]")
        api_key = Prompt.ask(f"Enter {env_key}", password=True)

    # 3. Detect iOS devices
    console.print("\n[bold]Step 3: Detecting iOS simulators and devices...[/bold]")
    from lunatap.drivers.ios.discovery import list_core_devices_sync, list_ios_simulators_sync

    booted = [
        d
        for d in (list_ios_simulators_sync() or [])
        if d.get("state") == "Booted" and d.get("udid")
    ]
    phones = [d for d in (list_core_devices_sync() or []) if d.get("udid")]
    if booted or phones:
        console.print("[bold green]✔ Found:[/bold green]")
        for device in booted:
            console.print(f"  Simulator  {device.get('name')}  ({device.get('udid')})")
        for device in phones:
            console.print(f"  Device     {device.get('name')}  ({device.get('udid')})")
        console.print(
            "[dim]Tasks use the booted simulator by default; pass --device-serial <UDID> "
            "for another simulator or a paired iPhone/iPad.[/dim]"
        )
    else:
        console.print(
            "[bold yellow]⚠ No booted simulator or paired device detected right now.[/bold yellow]\n"
            "[dim]Pass --device-serial <UDID> to run on a simulator; Lunatap boots it.[/dim]"
        )

    # 4. Generate .env File
    env_content = [
        "# ==============================================================================",
        "# Lunatap environment configuration (generated by 'lunatap init')",
        "# ==============================================================================",
        f"{env_key}={api_key.strip()}",
    ]
    if env_key == "OPENAI_API_KEY":
        env_content.append("LUNATAP_LLM_PRESET=openai")
    env_content.extend(
        [
            "",
            "# Execution Defaults",
            "LUNATAP_DEFAULT_PROFILE=pro",
            "LUNATAP_TRACES_DIR=./traces",
            "",
        ]
    )

    env_path = get_env_file()
    env_path.parent.mkdir(parents=True, exist_ok=True)
    env_path.write_text("\n".join(env_content), encoding="utf-8")

    # 5. Configure MCP for AI IDEs
    console.print("\n[bold]Step 5: Connect Lunatap to your AI IDE (MCP)[/bold]")
    console.print("  [1] Antigravity / Jetski (Recommended - Default)")
    console.print("  [2] Cursor")
    console.print("  [3] Claude Desktop / Claude Code")
    console.print("  [4] Windsurf")
    console.print("  [5] VS Code / Cline / Roo Code")
    console.print("  [6] Codex")
    console.print("  [7] All supported IDEs")
    console.print("  [8] Skip for now")
    mcp_choice = Prompt.ask(
        "Select IDE for MCP auto-install",
        choices=["1", "2", "3", "4", "5", "6", "7", "8"],
        default="1",
    )
    if mcp_choice != "8":
        target_map = {
            "1": "antigravity",
            "2": "cursor",
            "3": "claude",
            "4": "windsurf",
            "5": "vscode",
            "6": "codex",
            "7": "all",
        }
        target = target_map.get(mcp_choice, "antigravity")
        try:
            from lunatap.interfaces.cli.commands.mcp import install_mcp_config
            from mcp_server.utils import env_utils

            proj_root = env_utils.get_project_root()
            py_exe = env_utils.resolve_python_executable(proj_root)
            installed_paths = install_mcp_config(target, py_exe, proj_root)
            console.print(
                f"[bold green]✔ Configured Lunatap MCP in {len(installed_paths)} IDE location(s).[/bold green]"
            )
        except Exception as e:
            console.print(f"[yellow]Could not auto-install MCP config: {e}[/yellow]")

    console.print()
    console.print(
        Panel(
            f"[bold green]🎉 Setup completed successfully![/bold green]\n\n"
            f"Configured [bold cyan]{provider_name}[/bold cyan] in [dim]{env_path}[/dim]\n\n"
            "Try running your first task:\n"
            '  [bold cyan]uv run lunatap run "Open Settings and report the iOS version"[/bold cyan]\n\n'
            "Or connect/update your AI IDE anytime with:\n"
            "  [bold cyan]uv run lunatap mcp --install all[/bold cyan]\n\n"
            "Or run health diagnostics anytime with:\n"
            "  [bold cyan]uv run lunatap doctor[/bold cyan]",
            title="☕ Ready to Go!",
            expand=False,
        )
    )
    console.print()
